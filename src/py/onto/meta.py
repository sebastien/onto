"""Module: meta — an ontology described as observations of its own `Meta` domain (spec-01)."""

from __future__ import annotations

import re

from .observations.formatter import printText
from .ontology import BUILTINS, MULTI, Attr, Decl, Model, Ontology, TypeExpr
from .observations.model import Observations, ObservationsDocument
from .text import Diagnostic, Diagnostics, Loc

# -----------------------------------------------------------------------------
#
# DEFINITIONS
#
# -----------------------------------------------------------------------------

META_DOMAIN = "Meta"
CONCEPT_KINDS = {"entity": "Entity", "facet": "Facet", "relation": "Relation"}
# NOTE: Cardinalities are explicit, so the declarations mean the same under any `card` default.
META_DECLARATIONS = """\
// Meta: this ontology described as data, so that other elements can refer to its concepts,
// attributes and dimensions instead of copying their paths or values.
//
// Generated by `onto meta --decl`; the instances are generated by `onto meta`. Do not edit.

@domain Meta                                    -- The ontology described as data: its concepts, attributes and dimensions; generated, never hand-written

Meta/Path = Text                                -- Path of an element relative to the ontology namespace, e.g. Society/Person or Society/Person.DateOfBirth
Meta/Concept/Kind = Entity|Facet|Relation
Meta/Dimension/Kind = Builtin|Vocabulary|Value|Structure|Range -- Builtin: a type of the format, such as Text or Date; Vocabulary: a set of named values; Value: a named scalar based on another dimension; Structure: a composite of fields; Range: a low and a high bound of the dimension it is based on

Meta/Concept {layer=Reference}                  -- Something that has attributes: an entity, a facet or a relation; a binary relation is listed when it has attributes
  1 Path Meta/Path {id=key}
  1 Kind Meta/Concept/Kind
  ? Description Text                            -- Doc string of the concept

Meta/Dimension {layer=Reference}                -- A type that values are taken from: a builtin, a named type, or the vocabulary written in an attribute
  1 Path Meta/Path {id=key}                     -- Type path or builtin name; the attribute path for a vocabulary written in an attribute
  ? Kind Meta/Dimension/Kind                    -- Absent when the type is not defined yet
  * Values Text                                 -- Values of a vocabulary
  ? IsOpen Boolean                              -- Vocabulary that accepts values beyond those listed
  ? IsOrdered Boolean                           -- Vocabulary whose values are ranked; the ranking is the declaration's, as collections are unordered
  ? Description Text                            -- Doc string of the type

Meta/Attribute {layer=Reference}                -- An attribute of a concept, listed on the concept that declares it
  1 Path Meta/Path {id=key}                     -- Concept path and attribute name, e.g. Society/Person.DateOfBirth
  1 IsRequired Boolean                          -- At least one value is expected
  1 IsMultiple Boolean                          -- Several values are accepted
  ? Description Text                            -- Doc string of the attribute

Meta/Concept -hasAttribute/isAttributeOf-> Meta/Attribute 1:*
Meta/Attribute -hasDimension/isDimensionOf-> Meta/Dimension *:? -- Absent when the attribute refers to a concept or its type is not defined yet
Meta/Dimension -isBasedOn/isBaseOf-> Meta/Dimension *:? -- The dimension a named type is defined as: Core/Percentage is based on Number; a range is based on the dimension of its bounds
Meta/Dimension -extends/isExtendedBy-> Meta/Dimension *:? -- The open vocabulary a later domain adds its values to; the extended vocabulary lists them too
"""

# -----------------------------------------------------------------------------
#
# OPERATIONS
#
# -----------------------------------------------------------------------------


class MetaWriter:
	"""Writes the concepts, attributes and dimensions of an ontology as `Meta` observations."""

	def __init__(self, ontology: Ontology):
		self.ontology = ontology
		self.model = Model(ontology)
		self.prefix = re.compile(rf"(^|\.){re.escape(ontology.namespace or '')}/")
		self.dimensions: dict[str, list[str]] = {}
		self.bases: list[tuple[str, str]] = []
		self.extensions: list[tuple[str, str]] = []
		self.concepts: list[str] = []
		self.links: list[str] = []

	def path(self, path: str) -> str:
		"""`path` relative to the ontology namespace; a binary relation keeps its `S.verb.T` form."""
		return self.prefix.sub(r"\1", path)

	@staticmethod
	def Handle(path: str) -> str:
		"""The handle of the element at relative `path`: `/` becomes `_` and `.` becomes `__`."""
		return path.replace("/", "_").replace(".", "__")

	@staticmethod
	def Record(handle: str, type: str, values: list[tuple[str, str | None]]) -> list[str]:
		"""A record of `type` with the `values` that are stated."""
		return [f"{handle}:{META_DOMAIN}/{type}"] + [f"  {name} {value}" for name, value in values if value is not None]

	@staticmethod
	def Text(value: str | None) -> str | None:
		return printText(value) if value else None

	@staticmethod
	def Flag(value: bool) -> str:
		return "true" if value else "false"

	def vocabulary(self, definition: TypeExpr, ordered: bool = False, values: list[str] | None = None) -> list[tuple[str, str | None]]:
		"""The values of a vocabulary type expression, or `values` when given (a vocabulary with its extensions)."""
		values = ", ".join(printText(value, True) for value in (definition.values or [] if values is None else values))
		return [("Kind", "Vocabulary"), ("Values", f"[{values}]"), ("IsOpen", self.Flag(definition.open or definition.unknown)), ("IsOrdered", self.Flag(ordered))]

	def dimension(self, type: TypeExpr | None, owner: str) -> str | None:
		"""The handle of the dimension `type` denotes, recording it; `owner` names a vocabulary written in place."""
		if not type:
			return None
		if type.builtin:
			if type.builtin not in self.dimensions:
				self.dimensions[type.builtin] = self.Record(type.builtin, "Dimension", [("Path", type.builtin), ("Kind", "Builtin")])
			return type.builtin
		if type.range:
			return self.range(type.range)
		if type.values is not None or type.unknown:
			handle = f"{self.Handle(owner)}__Values"
			self.dimensions[handle] = self.Record(handle, "Dimension", [("Path", owner), *self.vocabulary(type)])
			return handle
		if type.attr:
			# NOTE: Attribute reuse (`Owner.Attr`) takes the dimension of the reused attribute.
			attr = self.model.lookup(type.path or "", type.attr)
			return self.dimension(attr.type, f"{self.path(type.path or '')}.{type.attr}") if attr else None
		decl = self.model.get(type.path)
		return self.named(decl) if decl and decl.kind == "type" else None

	def range(self, element: TypeExpr) -> str | None:
		"""The handle of the dimension `Range<element>`, recording it; one per element type."""
		base = self.dimension(element, "")
		if not base:
			return None
		handle = f"{base}__Range"
		if handle not in self.dimensions:
			name = element.builtin or self.path(element.path or "") + (f".{element.attr}" if element.attr else "")
			self.dimensions[handle] = self.Record(handle, "Dimension", [("Path", f"Range<{name}>"), ("Kind", "Range")])
			self.bases.append((handle, base))
		return handle

	def named(self, decl: Decl) -> str:
		"""The handle of the dimension of type declaration `decl`, recording it."""
		path = self.path(decl.path)
		handle = self.Handle(path)
		if handle in self.dimensions:
			return handle
		# NOTE: Recorded before its base is resolved, so that an alias cycle ends.
		self.dimensions[handle] = []
		definition = decl.definition
		values: list[tuple[str, str | None]] = [("Path", path)]
		final = self.model.typeDecl(TypeExpr(path=decl.path)) or decl
		if final.fields is not None:
			values.append(("Kind", "Structure"))
		elif final.definition and final.definition.range:
			values.append(("Kind", "Range"))
		elif final.definition and (final.definition.values is not None or final.definition.unknown):
			values += self.vocabulary(final.definition, any(key == "ordered" for key, _ in final.ann), self.model.resolveType(TypeExpr(path=final.path)).values)
		elif definition:
			values.append(("Kind", "Value"))
		if definition and (definition.builtin or definition.path or definition.range):
			base = self.dimension(definition.range or definition, path)
			if base:
				self.bases.append((handle, base))
		extended = self.model.get(next((value for key, value in decl.ann if key == "extends" and isinstance(value, str)), None))
		if extended and extended.kind == "type":
			self.extensions.append((handle, self.named(extended)))
		self.dimensions[handle] = self.Record(handle, "Dimension", values + [("Description", self.Text(decl.doc))])
		return handle

	def concept(self, decl: Decl) -> None:
		"""Record concept `decl` and its own attributes."""
		path = self.path(decl.path)
		handle = self.Handle(path)
		self.concepts += self.Record(handle, "Concept", [("Path", path), ("Kind", CONCEPT_KINDS[decl.kind]), ("Description", self.Text(decl.doc))])
		for attr in decl.attrs:
			self.attribute(handle, path, attr)

	def attribute(self, concept: str, conceptPath: str, attr: Attr) -> None:
		path = f"{conceptPath}.{attr.name}"
		handle = self.Handle(path)
		card = attr.card or self.model.defaultCard
		self.concepts += self.Record(handle, "Attribute", [
			("Path", path), ("IsRequired", self.Flag(card in ("1", "+"))), ("IsMultiple", self.Flag(card in MULTI)), ("Description", self.Text(attr.doc)),
		])
		self.links.append(f"{concept} hasAttribute {handle}")
		dimension = self.dimension(attr.type, path)
		if dimension:
			self.links.append(f"{handle} hasDimension {dimension}")

	def write(self) -> str:
		"""The observations document."""
		for decl in sorted(self.ontology.decls, key=lambda decl: decl.path):
			if decl.kind == "type":
				self.named(decl)
			elif decl.kind in CONCEPT_KINDS and (decl.kind != "relation" or decl.attrs or not decl.arrow):
				self.concept(decl)
		header = dict(self.ontology.header)
		namespace = self.ontology.namespace
		lines = [
			f"@obs {namespace}" + (f" rev={header['rev']}" if "rev" in header else ""),
			f"@scope onto:{namespace}",
			f"@src meta=onto:meta/{namespace}",
			"@src meta",
			"",
		]
		# NOTE: Builtins are not declarations of the ontology: they sort first, in the format's order.
		order = {name: index for index, name in enumerate(BUILTINS)}
		for handle in sorted(self.dimensions, key=lambda handle: (order.get(handle, len(order)), handle)):
			lines += self.dimensions[handle]
		lines += [f"{handle} isBasedOn {base}" for handle, base in sorted(self.bases)]
		lines += [f"{handle} extends {target}" for handle, target in sorted(self.extensions)]
		return "\n".join(lines + self.concepts + self.links) + "\n"


